export const IPTV_EPG_COUNTRIES = IPTV_EPG_COUNTRY_CODES.map((code) => ({
  code,
  name:
    IPTV_ORG_COUNTRIES.find(
      (country) => country.code === (code === 'gb' ? 'uk' : code)
    )?.name ?? code.toUpperCase(),
}));

const countrySchema = (codes: readonly string[], defaultCountry: string) =>
  z
    .string()
    .trim()
    .toLowerCase()
    .transform((code) =>
      defaultCountry === 'uk' && code === 'gb'
        ? 'uk'
        : defaultCountry === 'gb' && code === 'uk'
          ? 'gb'
          : code
    )
    .refine((code) => codes.includes(code), 'Unsupported country');

const common = {
  timeout: z.number().int().positive(),
  maxBytes: z.number().int().positive().optional(),
};

export const IptvOrgConfigSchema = z.object({
  ...common,
  country: countrySchema(
    IPTV_ORG_COUNTRIES.map((country) => country.code),
    'uk'
  ).default('uk'),
});

export const IptvEpgConfigSchema = z.object({
  ...common,
  country: countrySchema(IPTV_EPG_COUNTRY_CODES, 'gb').default('gb'),
  timeShiftMinutes: z.number().int().min(-720).max(720).default(0),
});

export type IptvOrgConfig = z.infer<typeof IptvOrgConfigSchema>;
export type IptvEpgConfig = z.infer<typeof IptvEpgConfigSchema>;

export const iptvOrgSourceUrl = (country: string) =>
  `https://iptv-org.github.io/iptv/countries/${IptvOrgConfigSchema.shape.country.parse(country)}.m3u`;

export const iptvEpgSourceUrl = (country: string) =>
  `https://iptv-epg.org/files/epg-${IptvEpgConfigSchema.shape.country.parse(country)}.xml.gz`;
